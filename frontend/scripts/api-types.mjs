// Regenerates src/lib/api/schema.ts from the FastAPI OpenAPI document, so the
// frontend's request/response types always match the real backend.
//
//   npm run api:types              write the file
//   npm run api:types -- --check   exit 1 if it is out of date (scripts/test.sh)
//
// Needs the backend's virtualenv (uv). No server, database or .env is used.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const backendDir = fileURLToPath(new URL("../../backend/", import.meta.url));
const target = fileURLToPath(new URL("../src/lib/api/schema.ts", import.meta.url));

const document = execFileSync("uv", ["run", "--frozen", "python", "-m", "app.cli.openapi"], {
  cwd: backendDir,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});
const ast = await openapiTS(JSON.parse(document), { alphabetize: true });
const output =
  "// Generated by `npm run api:types` from the FastAPI OpenAPI document. Do not edit by hand.\n\n" +
  astToString(ast);

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== output) {
    console.error("src/lib/api/schema.ts is out of date. Run: npm run api:types");
    process.exit(1);
  }
  console.log("API types are up to date.");
} else {
  writeFileSync(target, output);
  console.log("Wrote src/lib/api/schema.ts");
}
